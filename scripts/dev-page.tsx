import { mkdir, readFile, writeFile } from "node:fs/promises";
import { formatDiagnostics, render } from "@hyper-elements/react";
import { carePage } from "../templates/pages/care-page/template";
import { brand } from "../templates/_brands/kin";
import { shoot, closeBrowser } from "./shot";
const family = process.argv[2] ?? "sharma";
const care = JSON.parse(await readFile(`families/${family}.care.json`, "utf8"));
const checked = carePage(brand).check({ ...care, papersUrl: `https://kin.family/${family}/papers` });
console.log(formatDiagnostics(checked.diagnostics) || "no diagnostics");
if (!checked.valid) process.exit(1);
const { html } = await render(checked.snapshots.default!);
await mkdir("out", { recursive: true }); await writeFile(`out/${family}-page.html`, html);
await shoot(html, `out/${family}-page.png`, { width: 1200, scale: 1 });
await shoot(html, `out/${family}-page-phone.png`, { width: 390, scale: 1 });
await closeBrowser();
