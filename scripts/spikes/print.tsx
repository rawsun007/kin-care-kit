import { readFile } from "node:fs/promises";
import { execSync } from "node:child_process";
import { render } from "@hyper-elements/react";
import { fridgeChart } from "../../templates/documents/fridge-chart/template";
import { brand } from "../../templates/_brands/kin";
import { printPdf, closeBrowser } from "../shot";
const fam = process.argv[2] ?? "haddad";
const c = fridgeChart(brand).check(JSON.parse(await readFile(`families/${fam}.care.json`, "utf8")));
const { html } = await render(c.snapshots.default!);
await printPdf(html, `out/${fam}-print.pdf`); await closeBrowser();
execSync(`pdftoppm -png -r 110 out/${fam}-print.pdf out/${fam}-print`); console.log(execSync(`pdfinfo out/${fam}-print.pdf | grep Pages`).toString());
